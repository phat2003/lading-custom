-- =====================================================================
-- 008 UP: Thêm trạng thái 'pending' cho subscription
--
-- LÝ DO:
--   Luồng thanh toán MoMo cần lưu đơn hàng NGAY khi user bấm "Nâng cấp",
--   trước khi khách thực sự trả tiền. Bản ghi đó chưa được hưởng quyền Pro
--   nên không thể là 'active', cũng chưa bị huỷ nên không phải 'cancelled'.
--   Thiếu trạng thái này thì INSERT lỗi: invalid input value for enum.
--
-- VÒNG ĐỜI:
--   pending --(webhook resultCode = 0)--> active
--   pending --(khách huỷ / thất bại)---> cancelled
--
-- LƯU Ý VỀ UNIQUE INDEX:
--   uq_subscription_active_per_user chỉ ràng buộc WHERE status = 'active',
--   nên user bấm "Nâng cấp" nhiều lần sinh nhiều bản pending là hợp lệ —
--   không cái nào đụng index. Đổi lại, phía service phải expire subscription
--   active cũ TRƯỚC khi kích hoạt cái mới, nếu không webhook sẽ vi phạm index.
--
-- KHÔNG bọc BEGIN/COMMIT: ALTER TYPE ... ADD VALUE bị cấm trong transaction
-- block ở PostgreSQL < 12, và ở PG >= 12 thì giá trị mới cũng không dùng được
-- ngay trong cùng transaction. Câu lệnh này tự nó đã atomic.
-- =====================================================================

ALTER TYPE subscription_status ADD VALUE IF NOT EXISTS 'pending';
